-- Roles & permissions scaffolding for sb-mono.
-- Mirrors np-mono's pattern: app_role + app_permission ENUMs, user_roles + role_permissions tables,
-- custom_access_token_hook injecting user_role JWT claim, authorize() helper for RLS.
--
-- Roles in v1: admin, free (default). pro is reserved for Phase 2 monetization (themes, branding).
-- Also installs the permission-gated INSERT/UPDATE/DELETE policies for matches/events,
-- which depend on public.authorize() defined below — so they belong in this migration, not 000.

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'app_role') THEN
    CREATE TYPE public.app_role AS ENUM (
      'admin',
      'free',
      'pro'
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'app_permission') THEN
    CREATE TYPE public.app_permission AS ENUM (
      'match.create',
      'match.update.own',
      'match.delete.own',
      'theme.use.free',
      'theme.use.pro',
      'branding.custom',
      'admin.users.manage_roles',
      'admin.themes.publish'
    );
  END IF;
END
$$;


CREATE TABLE IF NOT EXISTS public.user_roles (
    id        bigint generated by default as identity primary key,
    user_id   uuid references auth.users on delete cascade not null,
    role      app_role not null,
    unique (user_id, role)
);
COMMENT ON TABLE public.user_roles IS 'Application roles for each user.';

CREATE TABLE IF NOT EXISTS public.role_permissions (
    id           bigint generated by default as identity primary key,
    role         app_role not null,
    permission   app_permission not null,
    unique (role, permission)
);
COMMENT ON TABLE public.role_permissions IS 'Application permissions granted per role.';


-- Seed role → permission grants. Idempotent via ON CONFLICT.
INSERT INTO public.role_permissions (role, permission) VALUES
    ('free', 'match.create'),
